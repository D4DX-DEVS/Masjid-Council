// One-off migration: MongoDB -> D1 SQL.
//
//   node scripts/cloudflare/exportMongo.js <out.sql> <filesPublicUrl>
//
// Reads MONGODB_URI (and DO_SPACES_* for the old CDN host) from .env, dumps every collection
// the app uses as relaxed Extended JSON rows, and rewrites stored DigitalOcean Spaces urls to
// <filesPublicUrl>/<key>. Apply the output with
//   wrangler d1 execute masjid-council-db --remote --file <out.sql>
// after db/schema.sql. The file contains personal data: keep it out of the repo.
//
// D1 caps one SQL statement at 100 KB, and a publication with all its chapters runs past that,
// so large documents are assembled chunk by chunk (UPDATE ... doc = doc || '<chunk>') in an
// unindexed staging table — the unique indexes parse `doc` as JSON, which a half-written
// document is not — and copied over once complete.

require("dotenv").config({ path: require("path").join(__dirname, "../../.env"), quiet: true });
const fs = require("fs");
const mongoose = require("mongoose");
const { EJSON } = require("bson");
const { collections } = require("../../db/indexes");

const [outFile, filesPublicUrl] = process.argv.slice(2);
if (!outFile || !filesPublicUrl) {
  console.error("usage: node scripts/cloudflare/exportMongo.js <out.sql> <filesPublicUrl>");
  process.exit(1);
}

const bucket = process.env.DO_SPACES_BUCKET;
const region = String(process.env.DO_SPACES_ENDPOINT || "").replace(/^https?:\/\//, "").split(".")[0];
const cdn = String(process.env.DO_SPACES_CDN_ENDPOINT || "").replace(/^https?:\/\//, "").replace(/\/$/, "");
const OLD_HOSTS = [
  cdn,
  `${bucket}.${region}.cdn.digitaloceanspaces.com`,
  `${bucket}.${region}.digitaloceanspaces.com`,
].filter(Boolean);
const OLD_PATH_STYLE = `${region}.digitaloceanspaces.com/${bucket}`;
const target = filesPublicUrl.replace(/\/$/, "");

const CHUNK_CHARS = 20000; // <= 80 KB even at 4 bytes a character
const sqlString = (s) => `'${s.replace(/'/g, "''")}'`;

const chunks = (text) => {
  const out = [];
  let i = 0;
  while (i < text.length) {
    let end = Math.min(i + CHUNK_CHARS, text.length);
    const code = text.charCodeAt(end - 1);
    if (end < text.length && code >= 0xd800 && code <= 0xdbff) end -= 1; // keep surrogate pairs whole
    out.push(text.slice(i, end));
    i = end;
  }
  return out;
};

const rewriteUrls = (text, referencedKeys) => {
  let out = text;
  const patterns = [...OLD_HOSTS.map((h) => `https?://${h.replace(/\./g, "\\.")}/`), `https?://${OLD_PATH_STYLE.replace(/\./g, "\\.")}/`];
  for (const p of patterns) {
    out = out.replace(new RegExp(`${p}([^"'\\s)<>\\\\]+)`, "g"), (_m, encodedKey) => {
      referencedKeys.add(decodeURI(encodedKey));
      return `${target}/${encodedKey}`;
    });
  }
  return out;
};

(async () => {
  await mongoose.connect(process.env.MONGODB_URI, { serverSelectionTimeoutMS: 15000 });
  const mdb = mongoose.connection.db;
  const referencedKeys = new Set();
  const lines = [
    "-- Generated by scripts/cloudflare/exportMongo.js",
    "DROP TABLE IF EXISTS _import;",
    "CREATE TABLE _import (_id TEXT PRIMARY KEY NOT NULL, doc TEXT NOT NULL);",
  ];
  const summary = {};

  for (const name of collections) {
    const docs = await mdb.collection(name).find({}).toArray();
    summary[name] = docs.length;
    lines.push(`DELETE FROM "${name}";`);
    for (const doc of docs) {
      const id = doc._id && doc._id._bsontype === "ObjectId" ? doc._id.toHexString() : typeof doc._id === "string" ? doc._id : EJSON.stringify(doc._id);
      const text = rewriteUrls(EJSON.stringify(doc, { relaxed: true }), referencedKeys);
      const [first, ...rest] = chunks(text);
      if (rest.length === 0) {
        lines.push(`INSERT INTO "${name}" (_id, doc) VALUES (${sqlString(id)}, ${sqlString(first)});`);
        continue;
      }
      lines.push(`INSERT INTO _import (_id, doc) VALUES (${sqlString(id)}, ${sqlString(first)});`);
      for (const part of rest) lines.push(`UPDATE _import SET doc = doc || ${sqlString(part)} WHERE _id = ${sqlString(id)};`);
      lines.push(`INSERT INTO "${name}" (_id, doc) SELECT _id, doc FROM _import WHERE _id = ${sqlString(id)};`);
      lines.push(`DELETE FROM _import WHERE _id = ${sqlString(id)};`);
    }
  }
  lines.push("DROP TABLE _import;");
  await mongoose.disconnect();

  const sql = lines.join("\n") + "\n";
  const leftovers = (sql.match(/digitaloceanspaces/g) || []).length;
  fs.writeFileSync(outFile, sql);
  fs.writeFileSync(outFile.replace(/\.sql$/, "") + ".keys.json", JSON.stringify([...referencedKeys].sort(), null, 2));
  console.log("documents per collection:", summary);
  console.log("referenced file keys:", referencedKeys.size, "| leftover digitaloceanspaces mentions:", leftovers);
})().catch((error) => {
  console.error(error);
  process.exit(1);
});
