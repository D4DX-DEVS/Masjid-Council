// Prints db/schema.sql from db/indexes.js:  node db/buildSchema.js > db/schema.sql
const { uniqueIndexes, objectIdFields, collections } = require("./indexes");

const expr = (collection, field, sparse) => {
  const path = (objectIdFields[collection] || []).includes(field) ? `$."${field}"."$oid"` : `$."${field}"`;
  const e = `json_extract(doc, '${path}')`;
  return sparse ? e : `coalesce(${e}, char(0))`;
};

const lines = ["-- Generated by db/buildSchema.js. One table per former MongoDB collection.", ""];
for (const c of collections) {
  lines.push(`CREATE TABLE IF NOT EXISTS "${c}" (_id TEXT PRIMARY KEY NOT NULL, doc TEXT NOT NULL);`);
  for (const idx of uniqueIndexes[c] || []) {
    const cols = Object.keys(idx.key).map((f) => expr(c, f, idx.sparse)).join(", ");
    lines.push(`CREATE UNIQUE INDEX IF NOT EXISTS "${idx.name}" ON "${c}" (${cols});`);
  }
  lines.push("");
}
process.stdout.write(lines.join("\n"));
